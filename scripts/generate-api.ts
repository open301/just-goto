import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { format, resolveConfig } from 'prettier';
import ts from 'typescript';

const base = process.env.JUSTGOTO_API_URL || 'http://127.0.0.1:3000';
const schema = new URL('/api-docs/openapi.json', base);
const output = new URL('../web/src/generated/api.ts', import.meta.url);
const outputPath = fileURLToPath(output);
const ast = await openapiTS(schema, {
	transform(schemaObject) {
		if (schemaObject.format === 'binary') {
			return ts.factory.createTypeReferenceNode('Blob');
		}
	},
});
const content = await format(
	'/** Generated by openapi-typescript. Run npm run generate:api. */\n' + astToString(ast),
	{ ...(await resolveConfig(outputPath)), filepath: outputPath },
);

if (process.argv.includes('--check')) {
	if ((await readFile(output, 'utf8')) !== content) {
		throw new Error('Generated API types are stale. Run npm run generate:api.');
	}
}
else {
	await mkdir(new URL('.', output), { recursive: true });
	await writeFile(output, content);
}
