import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { format, resolveConfig } from 'prettier';
import ts from 'typescript';

// Rust embeds the frontend; create missing placeholders for a fresh checkout.
const assets = new URL('../web/dist/assets/', import.meta.url);
await mkdir(assets, { recursive: true });
for (const path of [
	'../web/dist/index.html',
	'../web/dist/assets/app.js',
	'../web/dist/assets/app.css',
]) {
	await writeFile(new URL(path, import.meta.url), '', { flag: 'a' });
}
let schema: string;
if (process.env.JUSTGOTO_OPENAPI_FILE) {
	schema = await readFile(process.env.JUSTGOTO_OPENAPI_FILE, 'utf8');
}
else {
	schema = execFileSync('cargo', ['run', '--quiet', '--locked', '--', '--openapi'], {
		encoding: 'utf8',
	});
}
const output = new URL('../web/src/generated/api.ts', import.meta.url);
const outputPath = fileURLToPath(output);
const ast = await openapiTS(JSON.parse(schema), {
	transform(schemaObject) {
		if (schemaObject.format === 'binary') {
			return ts.factory.createTypeReferenceNode('Blob');
		}
	},
});
const content = await format('/** Generated by openapi-typescript. */\n' + astToString(ast), {
	...(await resolveConfig(outputPath)),
	filepath: outputPath,
});

await mkdir(new URL('.', output), { recursive: true });
await writeFile(output, content);
